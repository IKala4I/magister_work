/**
 * Generates the expected prior_cells v0 fixture for supabase/tests/p4_cold_start_test.sql
 * DIRECTLY from the File 04 §3.2–3.3 spec constants, independently of the seeding SQL in
 * supabase/migrations/20260824120300_seed_prior_cells_v0.sql. The pgTAP test asserts the
 * seeded table against this output, so the test encodes the spec, not the implementation
 * (owner directive, P4). Hand-checked cells: DM/deep/EM weekday = .78 (identity transform),
 * DM/admin/EM weekday = σ(0.45·logit(.78)+0.25) ≈ 0.6941567, INT/physical/AF weekday =
 * σ(0.55·logit(.62)+0.10+0.35) ≈ 0.6724425, DM/deep/EM weekend = .5·.78+.5·.55 = .665.
 *
 * Usage: node scripts/gen-prior-cells-expected.mjs > /tmp/prior_cells_expected.sql
 */

// File 04 §3.2 — Deep-work anchor matrix μ0_Deep(c0, p). Day-zero bootstrap values
// (re-fit quarterly by empirical Bayes per §3.5 — version 0 of a learned object).
const ANCHOR = {
  EM: { DM: 0.78, MM: 0.7, INT: 0.55, ME: 0.42, DE: 0.35 },
  MO: { DM: 0.74, MM: 0.72, INT: 0.66, ME: 0.55, DE: 0.48 },
  MD: { DM: 0.5, MM: 0.52, INT: 0.52, ME: 0.52, DE: 0.5 },
  AF: { DM: 0.55, MM: 0.58, INT: 0.62, ME: 0.64, DE: 0.62 },
  EV: { DM: 0.4, MM: 0.48, INT: 0.58, ME: 0.68, DE: 0.72 },
  NT: { DM: 0.3, MM: 0.36, INT: 0.48, ME: 0.62, DE: 0.74 },
};

// File 04 §3.3 — logit-affine category transform coefficients (γ_g, δ_g, δ_{g,p}).
// δ_{g,p} is nonzero only for physical in AF (circadian body-temperature peak).
const CATEGORIES = {
  deep: { gamma: 1.0, delta: 0.0, deltaAF: 0.0 },
  admin: { gamma: 0.45, delta: 0.25, deltaAF: 0.0 },
  physical: { gamma: 0.55, delta: 0.1, deltaAF: 0.35 },
  learning: { gamma: 0.85, delta: -0.05, deltaAF: 0.0 },
};

// File 04 §3.3 — prior strength n0 stored per day-type: 8 weekday base; weekend cells
// carry the "n0 halved" rule (4). Per-user multipliers (×0.5 outside working hours,
// ×0.5 on survey skip) are applied at beta_cells instantiation, not here.
const N0 = { weekday: 8, weekend: 4 };
// File 04 §3.3 — weekend blend target: μ0_wknd = ½·μ0_wkday + ½·0.55.
const WEEKEND_BLEND_TARGET = 0.55;

const logit = (p) => Math.log(p / (1 - p));
const sigma = (x) => 1 / (1 + Math.exp(-x));

const rows = [];
for (const [daypart, byClass] of Object.entries(ANCHOR)) {
  for (const [cls, muDeep] of Object.entries(byClass)) {
    for (const [cat, { gamma, delta, deltaAF }] of Object.entries(CATEGORIES)) {
      const bonus = daypart === 'AF' ? deltaAF : 0;
      const muWeekday = gamma === 1.0 && delta === 0 && bonus === 0
          ? muDeep // identity transform: the anchor passes through exactly
          : sigma(gamma * logit(muDeep) + delta + bonus);
      const muWeekend = 0.5 * muWeekday + 0.5 * WEEKEND_BLEND_TARGET;
      rows.push([cls, cat, daypart, 'weekday', muWeekday, N0.weekday]);
      rows.push([cls, cat, daypart, 'weekend', muWeekend, N0.weekend]);
    }
  }
}

rows.sort((a, b) => a.join('|').localeCompare(b.join('|')));
const values = rows
  .map(
    ([cls, cat, dp, dt, mu, n0]) =>
      `    ('${cls}','${cat}','${dp}','${dt}',${mu.toFixed(7)},${n0})`,
  )
  .join(',\n');

process.stdout.write(
  `-- GENERATED by scripts/gen-prior-cells-expected.mjs — do not hand-edit (${rows.length} rows)\n` +
    `insert into expected_prior_cells (chronotype_class, category, daypart, day_type, mu0, n0) values\n` +
    values +
    ';\n',
);
